import "./pages.css";

export default function PublicationEthics() {
  return (
    <section
      className="publication-ethics"
      aria-labelledby="publication-ethics-title"
    >
      <h2 id="publication-ethics-title">
        Regulamin Etyki Publikacji i Postępowania w Przypadkach Nierzetelności
      </h2>
      <p>
        Czasopismo naukowo-artystyczne “KonserwacjaWRO Szkło Witraż Ceramika”
      </p>
      <p>Akademia Sztuk Pięknych im. Eugeniusza Gepperta we Wrocławiu</p>
      <h3>I. Postanowienia ogólne</h3>
      <h4>1. Cel i zakres</h4>
      <p>
        Niniejszy Regulamin określa zasady etyczne obowiązujące Autorów,
        Recenzentów, Redakcję i Wydawcę czasopisma „KonserwacjaWRO”. Ma na celu
        zapewnienie najwyższych standardów rzetelności naukowej i artystycznej,
        integralności procesu publikacyjnego oraz sprawnego i uczciwego
        postępowania w sytuacjach nierzetelnych praktyk publikacyjnych.
      </p>
      <h4>2. Standardy etyczne</h4>
      <p>
        „KonserwacjaWRO” opiera swoje zasady na międzynarodowych standardach
        etyki publikacyjnej, w szczególności Code of Conduct and Best Practice
        Guidelines for Journal Editors oraz COPE Ethical Guidelines for Peer
        Reviewers, a także na dobrych praktykach edytorskich czasopism
        humanistycznych i artystycznych.
      </p>
      <h4>3. Zastosowanie</h4>
      <p>
        Regulamin ma zastosowanie na wszystkich etapach procesu publikacyjnego:
        zgłoszenia pracy, recenzji, decyzji redakcyjnych, publikacji oraz po
        publikacji.
      </p>
      <h3>II. Zasady etyczne obowiązujące Autorów</h3>
      <h4>1. Rzetelność naukowo-artystyczna</h4>
      <p>Autor zobowiązany jest do:</p>
      <ul>
        <li>
          prowadzenia badań lub analiz w sposób rzetelny, przejrzysty i
          obiektywny;
        </li>
        <li>
          przedstawiania interpretacji zgodnie z rzeczywistymi wynikami badań,
          analiz, materiałów źródłowych i dokumentacji;
        </li>
        <li>
          adekwatnego uzasadnienia twierdzeń oraz logicznego i wnikliwego
          uzasadnienia wniosków.
        </li>
      </ul>
      <h4>2. Oryginalność i własność intelektualna</h4>
      <ul>
        <li>
          Praca musi być oryginalna, nie może stanowić plagiatu ani autoplagatu
          (powielenia własnej, wcześniej opublikowanej pracy bez odpowiedniego
          oznaczenia).
        </li>
        <li>
          Niedopuszczalne jest przedstawianie cudzych treści, danych, pomysłów
          lub analiz jako własnych bez właściwego cytowania i uznania autorstwa
          źródła.
        </li>
      </ul>
      <h4>3. Odpowiednie cytowanie i rzetelność źródeł</h4>
      <ul>
        <li>
          Autor powinien cytować źródła, które miały istotny wpływ na jego pracę
          i tego wymagać będą normy wydawnicze czasopisma.
        </li>
        <li>
          Cytowania muszą być dokładne, adekwatne do treści oraz zgodne z
          przyjętym stylem cytowania.
        </li>
      </ul>
      <h4>4. Konflikt interesów</h4>
      <ul>
        <li>
          Autorzy zobowiązani są ujawnić wszelkie potencjalne konflikty
          interesów (np. finansowe, zawodowe, osobiste), które mogłyby być
          interpretowane jako wpływające na obiektywność lub postrzeganie
          wyników i wniosków.
        </li>
      </ul>
      <h4>5. Oświadczenia autorów</h4>
      <p>Zgłoszenie pracy do publikacji oznacza, że:</p>
      <ul>
        <li>
          praca nie była wcześniej publikowana ani nie została złożona do innego
          wydawnictwa;
        </li>
        <li>wszyscy autorzy znają i akceptują ostateczną wersję tekstu;</li>
        <li>
          autorzy potwierdzają, że praca nie narusza praw autorskich osób
          trzecich;
        </li>
        <li>
          autorzy deklarują brak nierzetelnych praktyk (plagiat, ghostwriting,
          guest authorship).
        </li>
      </ul>
      <h3>III. Zasady dotyczące Recenzentów</h3>
      <h4>1. Obiektywność i poufność recenzji</h4>
      <ul>
        <li>
          Recenzje mają charakter obiektywny, rzeczowy i merytoryczny oraz nie
          zawierają osobistych ocen o charakterze obraźliwym, niezwiązanych z
          jakością pracy Recenzowanego.
        </li>
        <li>
          Recenzent zachowuje poufność co do treści recenzowanych tekstów i nie
          ujawnia ich osobom trzecim.
        </li>
      </ul>
      <h4>2. Konflikt interesów recenzenta</h4>
      <ul>
        <li>
          Recenzent nie powinien uczestniczyć w ocenie pracy, jeśli istnieje
          realny lub potencjalny konflikt interesów (np. współpraca z autorem,
          relacje prywatne lub zawodowe).
        </li>
      </ul>
      <h4>3. Obowiązki recenzenta</h4>
      <ul>
        <li>
          Recenzent informuje Redakcję o naruszeniach etycznych lub
          podejrzeniach nierzetelności, takich jak plagiat czy niewłaściwa lista
          autorów.
        </li>
      </ul>
      <h3>IV. Zasady dotyczące Redakcji i Wydawcy</h3>
      <h4>1. Niezależność i bezstronność</h4>
      <ul>
        <li>
          Redakcja zobowiązuje się do podejmowania decyzji o publikacji
          wyłącznie na podstawie jakości merytorycznej i zgodności pracy z
          profilem tematycznym czasopisma.
        </li>
        <li>
          Decyzje te są wolne od nacisków zewnętrznych, politycznych lub
          ekonomicznych.
        </li>
      </ul>
      <h4>2. Odpowiedzialność za proces publikacyjny</h4>
      <ul>
        <li>
          Redakcja odpowiada za prawidłowy przebieg procesu recenzyjnego oraz
          wdrożenie zasad etyki publikacyjnej.
        </li>
        <li>
          W przypadku podejrzeń nierzetelności, Redakcja podejmuje działania
          wyjaśniające zgodne z niniejszym Regulaminem.
        </li>
      </ul>
      <h4>3. Zapobieganie nierzetelności</h4>
      <ul>
        <li>
          Redakcja podejmuje działania prewencyjne, takie jak korzystanie z
          systemów antyplagiatowych lub innych narzędzi weryfikacji
          oryginalności materiałów.
        </li>
      </ul>
      <h3>V. Procedury w przypadkach naruszenia etyki</h3>
      <h4>1. Zgłaszanie naruszeń</h4>
      <ul>
        <li>
          Zarzuty dotyczące nierzetelności mogą zgłaszać autorzy, recenzenci,
          członkowie Redakcji i czytelnicy.
        </li>
        <li>
          Zgłoszenia przyjmowane są na piśmie (e-mail: mma@asp.wroc.pl) i
          dokumentowane.
        </li>
      </ul>
      <h4>2. Analiza i decyzje</h4>
      <p>Po otrzymaniu zgłoszenia Redakcja analizuje sprawę i:</p>
      <ul>
        <li>wzywa autora do wyjaśnienia wątpliwości;</li>
        <li>
          w razie potrzeby powołuje zewnętrznych ekspertów do oceny materiału;
        </li>
        <li>
          podejmuje decyzję o korekcie, sprostowaniu, erracie, wycofaniu lub
          odrzuceniu pracy.
        </li>
      </ul>
      <h4>3. Sankcje</h4>
      <p>W zależności od rodzaju naruszenia Redakcja może:</p>
      <ul>
        <li>publikować erratę lub sprostowanie;</li>
        <li>
          wycofać artykuł z publikacji (w formie elektronicznej i/lub
          drukowanej);
        </li>
        <li>
          poinformować instytucje afiliacyjne autora o stwierdzonych
          naruszeniach;
        </li>
        <li>
          w uzasadnionych przypadkach czasowo zawiesić możliwość publikowania.
        </li>
      </ul>
      <h4>4. Publiczne komunikaty</h4>
      <ul>
        <li>
          W przypadku wycofania materiału Redakcja publikuje stosowną informację
          o powodzie tej decyzji i udokumentowanym naruszeniu.
        </li>
      </ul>
      <h3>VI. Postanowienia końcowe</h3>
      <ol>
        <li>
          Regulamin Etyki publikacji jest integralną częścią procesu
          wydawniczego „KonserwacjaWRO” i obowiązuje wszystkich uczestników
          procesu wydawniczego.
        </li>
        <li>
          Redakcja zastrzega sobie prawo do okresowej aktualizacji Regulaminu w
          celu uwzględnienia nowych standardów etycznych i technicznych
          rozwiązań wspierających rzetelność publikacji.
        </li>
      </ol>
    </section>
  );
}
